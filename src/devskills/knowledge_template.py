def _excluded(relative: str, patterns: list[str]) -> bool:
    return any(fnmatch.fnmatch(relative, pattern) for pattern in patterns)


def discover_sources(config: dict) -> list[Path]:
    """Files to index: configured roots (recursive), single files and hidden roots like .claude/rules."""
    found: set[Path] = set()
    exclude = config["exclude"]

    def consider(path: Path) -> None:
        if not path.is_file() or path.is_symlink():
            return
        relative = path.relative_to(ROOT).as_posix()
        if SECRET_NAMES.match(path.name) or _excluded(relative, exclude):
            return
        found.add(path)

    for root_name in config["roots"]:
        base = ROOT / root_name
        if base.is_dir():
            for path in base.rglob("*"):
                if not any(part.startswith(".") for part in path.relative_to(base).parts):
                    consider(path)
    for root_name in config.get("hidden_roots", []):
        base = ROOT / root_name
        if base.is_dir():
            for path in base.rglob("*"):
                consider(path)
    for file_name in config["files"]:
        for path in ROOT.glob(file_name):
            consider(path)
    return sorted(found, key=lambda path: path.relative_to(ROOT).as_posix())


def header(source: Path, mirror: Path, note: str) -> str:
    relative = source.relative_to(ROOT).as_posix()
    return (f"# {source.name}\n\n- Original: [{relative}]({link(mirror, source)})\n"
            f"- Original SHA-256: `{sha256(source.read_bytes())}`\n- Contents: {note}\n"
            "- Verify exact wording, pages, cells and layout in the original. Credential values are `[REDACTED]`.\n\n---\n\n")


def rebase_markdown_links(text: str, source: Path, mirror: Path) -> str:
    """Point relative links in a mirrored Markdown file back at the original targets."""
    def replace(match: re.Match) -> str:
        url = match.group(2)
        parsed = urlsplit(url)
        if parsed.scheme or parsed.netloc or not parsed.path or url.startswith(("<", "#")) or any(char.isspace() for char in url):
            return match.group(0)
        target = link(mirror, source.parent / unquote(parsed.path), parsed.fragment)
        return f"{match.group(1)}{target})"

    return re.sub(r"(!?\[[^\]\n]*\]\()([^\n)]+)\)", replace, text)


class HtmlToMarkdown(HTMLParser):
    """Keep document order, headings, lists, code and table rows, with original line numbers."""

    BLOCKS = {"p", "div", "li", "pre", "blockquote", "h1", "h2", "h3", "h4", "h5", "h6", "tr", "dt", "dd", "caption"}

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.lines: list[str] = []
        self.buffer: list[str] = []
        self.block_tag: str | None = None
        self.block_line = 0
        self.skip_depth = 0
        self.row_cells: list[str] | None = None
        self.in_cell = False
        self.blocks = 0

    def handle_starttag(self, tag: str, attrs: list) -> None:
        if tag in ("script", "style", "noscript", "template"):
            self.skip_depth += 1
            return
        if tag == "tr":
            self.flush()
            self.row_cells = []
            self.block_line = self.getpos()[0]
        elif tag in ("td", "th") and self.row_cells is not None:
            self.in_cell = True
            self.buffer = []
        elif tag in self.BLOCKS:
            self.flush()
            self.block_tag = tag
            self.block_line = self.getpos()[0]
        elif tag == "br":
            self.buffer.append("\n")

    def handle_endtag(self, tag: str) -> None:
        if tag in ("script", "style", "noscript", "template"):
            self.skip_depth = max(0, self.skip_depth - 1)
            return
        if tag in ("td", "th") and self.row_cells is not None:
            self.row_cells.append(table_cell("".join(self.buffer)))
            self.buffer = []
            self.in_cell = False
        elif tag == "tr" and self.row_cells is not None:
            if any(self.row_cells):
                self.lines.append(f"<!-- line {self.block_line} -->")
                self.lines.append("| " + " | ".join(self.row_cells) + " |")
                self.blocks += 1
            self.row_cells = None
        elif tag in self.BLOCKS:
            self.flush()

    def handle_data(self, data: str) -> None:
        if not self.skip_depth:
            self.buffer.append(data)

    def flush(self) -> None:
        """Emit the buffered text as one Markdown block tagged with its source line."""
        if self.in_cell or self.row_cells is not None:
            return
        text = re.sub(r"[ \t]+", " ", "".join(self.buffer)).strip()
        self.buffer = []
        if not text:
            return
        tag = self.block_tag or "p"
        if tag.startswith("h") and tag[1:].isdigit():
            text = "#" * min(6, int(tag[1:]) + 1) + " " + text
        elif tag == "li":
            text = "- " + text
        elif tag == "pre":
            text = "```\n" + text + "\n```"
        self.lines.append(f"<!-- line {self.block_line} -->")
        self.lines.append(text)
        self.lines.append("")
        self.blocks += 1
        self.block_tag = None


def convert_html(source: Path) -> tuple[str, dict]:
    parser = HtmlToMarkdown()
    parser.feed(decode_text(source.read_bytes()))
    parser.flush()
    return "\n".join(parser.lines) + "\n", {"blocks": parser.blocks}


def convert_csv(source: Path, max_rows: int) -> tuple[str, dict]:
    """CSV/TSV as a Markdown table with record numbers, capped at csv_max_rows."""
    text = decode_text(source.read_bytes())
    delimiter = "\t" if source.suffix.lower() == ".tsv" else ","
    try:
        delimiter = csv.Sniffer().sniff(text[:4096], delimiters=",;\t").delimiter
    except csv.Error:
        pass  # Unknown dialect: keep the delimiter implied by the file extension.
    rows = list(csv.reader(io.StringIO(text), delimiter=delimiter))
    if not rows:
        return "_empty file_\n", {"rows": 0}
    width = max(len(row) for row in rows)
    lines = ["| # | " + " | ".join(table_cell(value) for value in rows[0] + [""] * (width - len(rows[0]))) + " |",
             "| --- |" + " --- |" * width]
    for record_number, row in enumerate(rows[1:max_rows + 1], start=1):
        lines.append(f"| {record_number} | " + " | ".join(table_cell(value) for value in row + [""] * (width - len(row))) + " |")
    if len(rows) - 1 > max_rows:
        lines.append(f"\n_{len(rows) - 1 - max_rows} more records not shown; open the original._")
    return "\n".join(lines) + "\n", {"rows": len(rows) - 1}


def _zip_part(archive: zipfile.ZipFile, name: str) -> ElementTree.Element | None:
    """Parse one XML part, refusing oversized parts and DTDs (entity expansion)."""
    try:
        info = archive.getinfo(name)
    except KeyError:
        return None
    if info.file_size > MAX_ZIP_PART_BYTES:
        raise ValueError(f"{name} is larger than {MAX_ZIP_PART_BYTES} bytes uncompressed")
    data = archive.read(name)
    if b"<!DOCTYPE" in data[:2048] or b"<!ENTITY" in data:
        raise ValueError(f"{name} declares a DTD; refusing to parse")
    return ElementTree.fromstring(data)


def _relationships(archive: zipfile.ZipFile, rels_name: str, base_dir: str) -> dict[str, str]:
    root = _zip_part(archive, rels_name)
    if root is None:
        return {}
    targets = {}
    for relation in root.findall("rel:Relationship", NS):
        target = relation.get("Target", "")
        targets[relation.get("Id")] = target.lstrip("/") if target.startswith("/") else str(PurePosixPath(base_dir) / target)
    return {key: os.path.normpath(value).replace(os.sep, "/") for key, value in targets.items()}


def convert_docx(source: Path) -> tuple[str, dict]:
    """DOCX paragraphs (¶N), headings, lists, tables and review comments read from the ZIP/XML parts."""
    with zipfile.ZipFile(source) as archive:
        document = _zip_part(archive, "word/document.xml")
        if document is None:
            raise ValueError("word/document.xml not found")
        body = document.find("w:body", NS)
        lines: list[str] = []
        paragraph_number = 0
        tables = 0

        def paragraph_text(paragraph: ElementTree.Element) -> str:
            parts = []
            for node in paragraph.iter():
                if node.tag == f"{{{NS['w']}}}t":
                    parts.append(node.text or "")
                elif node.tag == f"{{{NS['w']}}}tab":
                    parts.append("\t")
                elif node.tag in (f"{{{NS['w']}}}br", f"{{{NS['w']}}}cr"):
                    parts.append("\n")
            return "".join(parts).strip()

        for element in list(body) if body is not None else []:
            if element.tag == f"{{{NS['w']}}}p":
                paragraph_number += 1
                text = paragraph_text(element)
                if not text:
                    continue
                style = element.find("w:pPr/w:pStyle", NS)
                style_name = (style.get(f"{{{NS['w']}}}val") if style is not None else "") or ""
                heading = re.match(r"(?i)^(?:heading|見出し)\s*(\d)$", style_name) or (re.match(r"(?i)^title$", style_name) and re.match("(.*)", "1"))
                if heading:
                    text = "#" * min(6, int(heading.group(1)) + 1) + " " + text
                elif element.find("w:pPr/w:numPr", NS) is not None:
                    text = "- " + text
                lines += [f"<!-- ¶{paragraph_number} -->", text, ""]
            elif element.tag == f"{{{NS['w']}}}tbl":
                tables += 1
                lines.append(f"<!-- table {tables} (after ¶{paragraph_number}) -->")
                for row_index, row in enumerate(element.findall("w:tr", NS)):
                    cells = [table_cell(" ".join(paragraph_text(paragraph) for paragraph in cell.findall(".//w:p", NS)))
                             for cell in row.findall("w:tc", NS)]
                    lines.append("| " + " | ".join(cells) + " |")
                    if row_index == 0:
                        lines.append("|" + " --- |" * len(cells))
                lines.append("")
        comments = _zip_part(archive, "word/comments.xml")
        comment_count = 0
        if comments is not None:
            items = comments.findall("w:comment", NS)
            if items:
                lines += ["## Review comments", ""]
                for comment in items:
                    comment_count += 1
                    author = comment.get(f"{{{NS['w']}}}author", "?")
                    text = " ".join(paragraph_text(paragraph) for paragraph in comment.findall(".//w:p", NS))
                    lines.append(f"- **{author}**: {text}")
                lines.append("")
    return "\n".join(lines) + "\n", {"paragraphs": paragraph_number, "tables": tables, "comments": comment_count}


def _column_letters(reference: str) -> tuple[str, int]:
    match = re.match(r"([A-Z]+)(\d+)", reference)
    return (match.group(1), int(match.group(2))) if match else ("A", 0)


def _column_index(letters: str) -> int:
    index = 0
    for letter in letters:
        index = index * 26 + (ord(letter) - 64)
    return index


def _column_name(index: int) -> str:
    name = ""
    while index:
        index, remainder = divmod(index - 1, 26)
        name = chr(65 + remainder) + name
    return name


def convert_xlsx(source: Path, grid_max_cells: int) -> tuple[str, dict, dict]:
    """Every sheet (hidden ones marked) as a grid or cell list; types/formulas/merges go to data JSON."""
    with zipfile.ZipFile(source) as archive:
        workbook = _zip_part(archive, "xl/workbook.xml")
        if workbook is None:
            raise ValueError("xl/workbook.xml not found")
        relations = _relationships(archive, "xl/_rels/workbook.xml.rels", "xl")
        shared_root = _zip_part(archive, "xl/sharedStrings.xml")
        shared_strings = []
        if shared_root is not None:
            for item in shared_root.findall("s:si", NS):
                shared_strings.append("".join(node.text or "" for node in item.iter(f"{{{NS['s']}}}t")))
        lines: list[str] = []
        data_sheets = []
        total_cells = 0
        sheets = workbook.findall("s:sheets/s:sheet", NS)
        for sheet in sheets:
            name = sheet.get("name", "?")
            state = sheet.get("state", "visible")
            part = relations.get(sheet.get(f"{{{NS['r']}}}id"), "")
            sheet_root = _zip_part(archive, part) if part else None
            cells: dict[str, dict] = {}
            merged: list[str] = []
            if sheet_root is not None:
                for cell in sheet_root.iter(f"{{{NS['s']}}}c"):
                    reference = cell.get("r", "")
                    cell_type = cell.get("t", "n")
                    value_node = cell.find("s:v", NS)
                    formula_node = cell.find("s:f", NS)
                    value = value_node.text if value_node is not None else None
                    if cell_type == "s" and value is not None and value.isdigit() and int(value) < len(shared_strings):
                        value = shared_strings[int(value)]
                    elif cell_type == "inlineStr":
                        value = "".join(node.text or "" for node in cell.iter(f"{{{NS['s']}}}t"))
                    elif cell_type == "b" and value is not None:
                        value = "TRUE" if value == "1" else "FALSE"
                    if value is None and formula_node is None:
                        continue
                    entry = {"t": cell_type, "v": redact(value) if isinstance(value, str) else value}
                    if formula_node is not None and formula_node.text:
                        entry["f"] = formula_node.text
                    cells[reference] = entry
                merged = [item.get("ref", "") for item in sheet_root.iter(f"{{{NS['s']}}}mergeCell")]
            total_cells += len(cells)
            label = f"## Sheet: {name}" + (f" ({state})" if state != "visible" else "")
            lines += [label, "", f"- cells with values: {len(cells)}; merged ranges: {len(merged)}", ""]
            if cells:
                positions = [_column_letters(reference) for reference in cells]
                columns = sorted({_column_index(letters) for letters, _ in positions})
                rows = sorted({row for _, row in positions})
                grid_size = len(columns) * len(rows)
                if grid_size <= grid_max_cells and len(columns) <= 40:
                    lines.append("| Row | " + " | ".join(_column_name(column) for column in columns) + " |")
                    lines.append("| --- |" + " --- |" * len(columns))
                    for row in rows:
                        values = [table_cell(cells.get(f"{_column_name(column)}{row}", {}).get("v")) for column in columns]
                        lines.append(f"| {row} | " + " | ".join(values) + " |")
                else:
                    for reference, entry in sorted(cells.items(), key=lambda item: (_column_letters(item[0])[1], _column_index(_column_letters(item[0])[0]))):
                        lines.append(f"- {reference}: {table_cell(entry.get('v'))}")
                formulas = [(reference, entry["f"]) for reference, entry in cells.items() if "f" in entry]
                if formulas:
                    lines += ["", f"Formulas ({len(formulas)}, first 200):", ""]
                    lines += [f"- {reference}: `={formula}`" for reference, formula in formulas[:200]]
            lines.append("")
            data_sheets.append({"name": name, "state": state, "part": part, "merged": merged, "cells": cells})
    return "\n".join(lines) + "\n", {"sheets": len(sheets), "cells": total_cells}, {"sheets": data_sheets}


def convert_pptx(source: Path) -> tuple[str, dict]:
    """Slide text in presentation order, plus speaker notes when present."""
    with zipfile.ZipFile(source) as archive:
        presentation = _zip_part(archive, "ppt/presentation.xml")
        relations = _relationships(archive, "ppt/_rels/presentation.xml.rels", "ppt")
        lines: list[str] = []
        slide_ids = presentation.findall("p:sldIdLst/p:sldId", NS) if presentation is not None else []
        for number, slide_id in enumerate(slide_ids, start=1):
            part = relations.get(slide_id.get(f"{{{NS['r']}}}id"), "")
            slide = _zip_part(archive, part) if part else None
            lines += [f"## Slide {number}", ""]
            if slide is not None:
                for paragraph in slide.iter(f"{{{NS['a']}}}p"):
                    text = "".join(node.text or "" for node in paragraph.iter(f"{{{NS['a']}}}t")).strip()
                    if text:
                        lines.append(f"- {text}")
                slide_relations = _relationships(archive, str(PurePosixPath(part).parent / "_rels" / (PurePosixPath(part).name + ".rels")),
                                                 str(PurePosixPath(part).parent))
                for target in slide_relations.values():
                    if "notesSlide" in target:
                        notes = _zip_part(archive, target)
                        note_lines = [] if notes is None else [
                            "".join(node.text or "" for node in paragraph.iter(f"{{{NS['a']}}}t")).strip()
                            for paragraph in notes.iter(f"{{{NS['a']}}}p")]
                        note_lines = [line for line in note_lines if line and not line.isdigit()]
                        if note_lines:
                            lines += ["", "Notes:"] + [f"> {line}" for line in note_lines]
            lines.append("")
    return "\n".join(lines) + "\n", {"slides": len(slide_ids)}


def convert_pdf(source: Path) -> tuple[str, dict]:
    from pypdf import PdfReader  # Optional dependency (requirements.txt); ImportError is reported as not converted.

    reader = PdfReader(str(source))
    lines: list[str] = []
    for number, page in enumerate(reader.pages, start=1):
        text = (page.extract_text() or "").strip()
        lines += [f"## Page {number}", "", text or "_no extractable text (scanned image?)_", ""]
    return "\n".join(lines) + "\n", {"pages": len(reader.pages)}


def convert(source: Path, mirror: Path, config: dict) -> tuple[str, dict, dict | None]:
    """Return (markdown body, counts, optional data JSON) for one source."""
    suffix = source.suffix.lower()
    if suffix in TEXT_SUFFIXES:
        text = decode_text(source.read_bytes())
        if suffix in (".md", ".markdown"):
            text = rebase_markdown_links(text, source, mirror)
        return text if text.endswith("\n") else text + "\n", {}, None
    if suffix in STRUCTURED_SUFFIXES:
        return f"```{STRUCTURED_SUFFIXES[suffix]}\n{decode_text(source.read_bytes()).rstrip()}\n```\n", {}, None
    if suffix in (".html", ".htm"):
        return (*convert_html(source), None)
    if suffix in (".csv", ".tsv"):
        return (*convert_csv(source, config["csv_max_rows"]), None)
    if suffix == ".docx":
        return (*convert_docx(source), None)
    if suffix == ".xlsx":
        return convert_xlsx(source, config["xlsx_grid_max_cells"])
    if suffix == ".pptx":
        return (*convert_pptx(source), None)
    if suffix == ".pdf":
        return (*convert_pdf(source), None)
    raise ValueError("unsupported format")


def category_of(relative: str, config: dict) -> str:
    for category in config["categories"]:
        if any(fnmatch.fnmatch(relative, pattern) for pattern in category["patterns"]):
            return category["name"]
    return "Documents"


def index_hash_text(text: str) -> str:
    """INDEX.md content with the manual block blanked, so hand edits there do not make it STALE."""
    return re.sub(re.escape(MANUAL_START) + r".*?" + re.escape(MANUAL_END), MANUAL_START + MANUAL_END, text, flags=re.DOTALL)


def render_index(config: dict, entries: list[dict], manual_block: str | None) -> str:
    """Render INDEX.md: fixed guidance, preserved manual block, one table per category, not-converted list."""
    strings = STRINGS[config["language"]]
    manual = manual_block if manual_block is not None else f"\n## {strings['manual_heading']}\n\n{strings['manual_body']}\n"
    lines = [
        f"# {config['title']}", "",
        "<!-- Generated by .knowledge/build.py. Edit only between the knowledge:manual markers; other content is regenerated. -->", "",
        f"## {strings['first_steps']}", "", f"1. {strings['step1']}", f"2. {strings['step2']}", f"3. {strings['step3']}", "",
        MANUAL_START + manual + MANUAL_END, "",
        f"## {strings['search']}", "", "```sh", "python3 .knowledge/build.py --check",
        "rg -n --glob '*.md' 'keyword' .knowledge/mirrors", "python3 .knowledge/build.py", "```", "",
        strings["search_note"], "",
        f"## {strings['accuracy']}", "",
    ]
    lines += [f"- {strings[key]}" for key in ("acc1", "acc2", "acc3", "acc4", "acc5")]
    converted = [entry for entry in entries if entry.get("markdown")]
    skipped = [entry for entry in entries if not entry.get("markdown")]
    category_names = [category["name"] for category in config["categories"]]
    for category_name in category_names + sorted({entry["category"] for entry in converted} - set(category_names)):
        rows = [entry for entry in converted if entry["category"] == category_name]
        if not rows:
            continue
        lines += ["", f"## {category_name}", "", f"| {strings['original']} | {strings['markdown']} | {strings['details']} |", "| --- | --- | --- |"]
        for entry in rows:
            source = ROOT / entry["source"]
            details = " / ".join(f"{key}: {value}" for key, value in entry["counts"].items()) or "text"
            lines.append(f"| [{table_cell(entry['source'])}]({link(HERE / 'INDEX.md', source)}) | "
                         f"[{strings['read']}]({quote(entry['markdown'], safe='/.-_~')}) | {details} |")
    if skipped:
        lines += ["", f"## {strings['not_converted']}", "", f"| {strings['original']} | {strings['reason']} |", "| --- | --- |"]
        for entry in skipped[:300]:
            lines.append(f"| [{table_cell(entry['source'])}]({link(HERE / 'INDEX.md', ROOT / entry['source'])}) | {table_cell(entry['status'])} |")
    return "\n".join(lines) + "\n"


def existing_manual_block() -> str | None:
    index_path = HERE / "INDEX.md"
    if not index_path.is_file():
        return None
    text = index_path.read_text(encoding="utf-8")
    match = re.search(re.escape(MANUAL_START) + r"(.*?)" + re.escape(MANUAL_END), text, re.DOTALL)
    return match.group(1) if match else None


def build() -> int:
    """Regenerate mirrors, data JSON, INDEX.md and manifest.json; delete outputs whose source disappeared."""
    config = load_config()
    sources = discover_sources(config)
    outputs: dict[Path, bytes] = {}
    entries: list[dict] = []
    for source in sources:
        relative = source.relative_to(ROOT).as_posix()
        entry = {"source": relative, "sha256": sha256(source.read_bytes()), "category": category_of(relative, config),
                 "markdown": None, "data": None, "counts": {}, "status": "converted"}
        suffix = source.suffix.lower()
        if suffix not in CONVERTIBLE_SUFFIXES:
            entry["status"] = f"{suffix or 'no extension'} files are not mirrored"
        elif source.stat().st_size > config["max_file_bytes"]:
            entry["status"] = f"larger than {config['max_file_bytes']} bytes"
        else:
            mirror_relative = f"mirrors/{relative}" if suffix in (".md", ".markdown") else f"mirrors/{relative}.md"
            mirror = HERE / mirror_relative
            try:
                body, counts, data = convert(source, mirror, config)
            except ImportError:
                entry["status"] = "PDF needs pypdf: python3 -m pip install -r .knowledge/requirements.txt"
            except (ValueError, KeyError, zipfile.BadZipFile, ElementTree.ParseError, UnicodeError) as error:
                entry["status"] = f"conversion failed: {str(error)[:120]}"
            else:
                outputs[mirror] = (header(source, mirror, ", ".join(f"{k} {v}" for k, v in counts.items()) or "text") + redact(body)).encode("utf-8")
                entry |= {"markdown": mirror_relative, "counts": counts}
                if data is not None:
                    data_relative = f"data/{relative}.json"
                    outputs[HERE / data_relative] = (json.dumps(data, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
                    entry["data"] = data_relative
        entries.append(entry)

    index_text = render_index(config, entries, existing_manual_block())
    outputs[HERE / "INDEX.md"] = index_text.encode("utf-8")
    for stale in [path for folder in ("mirrors", "data") for path in (HERE / folder).rglob("*") if path.is_file()] if True else []:
        if stale not in outputs:
            stale.unlink()
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_bytes() != content:
            path.write_bytes(content)
    manifest = {
        "format_version": FORMAT_VERSION,
        "script_sha256": sha256(Path(__file__).read_bytes()),
        "config_sha256": sha256(CONFIG_PATH.read_bytes()) if CONFIG_PATH.is_file() else None,
        "sources": [{key: value for key, value in entry.items() if key != "category"} for entry in entries],
        "outputs": {path.relative_to(HERE).as_posix(): sha256(index_hash_text(content.decode("utf-8")).encode("utf-8"))
                    if path.name == "INDEX.md" and path.parent == HERE else sha256(content)
                    for path, content in sorted(outputs.items())},
    }
    (HERE / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    converted = sum(1 for entry in entries if entry["markdown"])
    print(f"built: {converted} of {len(entries)} source files mirrored; {len(entries) - converted} listed as not converted")
    for entry in entries:
        if entry["status"] != "converted" and not entry["status"].endswith("not mirrored"):
            print(f"  note: {entry['source']}: {entry['status']}")
    return 0


def check() -> int:
    """Read-only: compare sources, script, config and generated files with manifest.json."""
    manifest_path = HERE / "manifest.json"
    if not manifest_path.is_file():
        print("STALE: manifest.json is missing\nRun: python3 .knowledge/build.py")
        return 1
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    errors: list[str] = []
    if manifest.get("format_version") != FORMAT_VERSION:
        errors.append("format version changed")
    if manifest.get("script_sha256") != sha256(Path(__file__).read_bytes()):
        errors.append("build.py changed")
    config_digest = sha256(CONFIG_PATH.read_bytes()) if CONFIG_PATH.is_file() else None
    if manifest.get("config_sha256") != config_digest:
        errors.append("config.json changed")
    recorded = {entry["source"]: entry for entry in manifest.get("sources", [])}
    current = {path.relative_to(ROOT).as_posix(): path for path in discover_sources(load_config())}
    for added in sorted(set(current) - set(recorded))[:20]:
        errors.append(f"new source: {added}")
    for removed in sorted(set(recorded) - set(current))[:20]:
        errors.append(f"source removed: {removed}")
    for relative in sorted(set(current) & set(recorded)):
        if sha256(current[relative].read_bytes()) != recorded[relative]["sha256"]:
            errors.append(f"source changed: {relative}")
    for relative, digest in manifest.get("outputs", {}).items():
        path = HERE / relative
        if not path.is_file():
            errors.append(f"generated file missing: {relative}")
            continue
        content = path.read_bytes()
        actual = sha256(index_hash_text(content.decode("utf-8")).encode("utf-8")) if relative == "INDEX.md" else sha256(content)
        if actual != digest:
            errors.append(f"generated file edited: {relative}")
    if errors:
        print("STALE\n" + "\n".join(f"- {error}" for error in errors[:50]) + "\nRun: python3 .knowledge/build.py")
        return 1
    print(f"CURRENT: {len(recorded)} source files; {len(manifest.get('outputs', {}))} generated files; SHA-256 checks passed")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="read-only freshness check (standard library only)")
    args = parser.parse_args()
    return check() if args.check else build()


if __name__ == "__main__":
    sys.exit(main())
