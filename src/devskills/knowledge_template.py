def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def redact(text: str) -> str:
    for pattern, replacement in _REDACTIONS:
        text = pattern.sub(replacement, text)
    return text


def decode_text(data: bytes) -> str:
    """UTF-8 first; UTF-16 only with a BOM; then Shift-JIS (cp932) for Japanese documents."""
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        return data.decode("utf-16")
    for encoding in ("utf-8-sig", "cp932"):
        try:
            return data.decode(encoding)
        except UnicodeDecodeError:
            continue
    return data.decode("latin-1")


def link(from_file: Path, to_file: Path, fragment: str = "") -> str:
    relative = os.path.relpath(to_file, from_file.parent).replace(os.sep, "/")
    return quote(relative, safe="/.-_~") + (f"#{fragment}" if fragment else "")


def table_cell(value: object) -> str:
    text = "" if value is None else str(value)
    return text.replace("|", "&#124;").replace("\r\n", "\n").replace("\n", "<br>").strip()


def load_config() -> dict:
    config = json.loads(json.dumps(DEFAULT_CONFIG))
    if CONFIG_PATH.is_file():
        user_config = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
        config.update(user_config)
